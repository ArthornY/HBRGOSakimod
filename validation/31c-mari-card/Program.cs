    static AllOrdersConfirmedHbrgoSaki Mari(params int[] effects)
    {
        var card = ClarityCard<AllOrdersConfirmedHbrgoSaki>();
        foreach (int id in effects)
        {
            Check((bool)Native(card, "PrepareUpgradeEffect", id)!, "Mari garden accepts effect " + id);
            card.UpgradeInternal(); card.FinalizeUpgradeInternal();
        }
        return card;
    }
