    public static void RunMari(string path)
    {
        bool ok=false;string? error=null;
        try
        {
            Install();Localization();var h=new Harmony(ProductionId+".mari55");
            foreach(Type type in new[]{typeof(AllOrdersConfirmedHbrgoSaki),typeof(WorldIsMyLaboratoryHbrgoSaki),typeof(WorldConquestHbrgoSaki)})
            {if(!ModelDb.Contains(type))ModelDb.Inject(type);Set(ModelDb.GetById<AbstractModel>(ModelDb.GetId(type)),"<Id>k__BackingField",ModelDb.GetId(type));}
            Check(h.CreateClassProcessor(Mod.GetType("HBRGOSakiMod.Core.Patches.Combat.MagicSwordLuckySevenPopulateCombatStatePatch",true)!).Patch().Count>0,"installs shared production noncombat-template setup filter");
            h.Patch(typeof(CombatState).GetMethod("IterateHookListeners",F)!,prefix:new HarmonyMethod(typeof(EffectChecks).GetMethod(nameof(TemplateAllListeners),F)!){priority=Priority.First+100});
            foreach(MethodInfo remove in typeof(CardPileCmd).GetMethods(F).Where(m=>m.Name=="RemoveFromCombat"))h.Patch(remove,prefix:new HarmonyMethod(typeof(EffectChecks).GetMethod(nameof(CrackRemove),F)!));
            MariCardCases(h).GetAwaiter().GetResult();ok=true;
        }
        catch(Exception ex){error=ex.ToString();Console.Error.WriteLine(ex);}
        File.WriteAllText(path,JsonSerializer.Serialize(new{ok,checks=Passed.Count,passed=Passed,error,modSha256=Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(Mod.Location))),runtimeProfile=Environment.GetEnvironmentVariable("HBR_NATIVE_PROFILE"),boundary="Actual garden seven-choice ledger, permanent owner-local policy, native PopulateCombatState cloning and shared template filter, actual OD/personal temporary-deck prepare/restore and shuffle/entry rejection. Only terminal pile-removal visual leaf is isolated; no Godot, UI, package or upload."},new JsonSerializerOptions{WriteIndented=true}));
        if(!ok)throw new Exception("Inspect "+path);Console.WriteLine("PASS "+Passed.Count+" Mari card checks");
    }
