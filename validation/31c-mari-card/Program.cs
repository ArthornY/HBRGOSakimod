        foreach (int id in new[] { 5, 2, 6, 4, 1, 3 })
        { Check((bool)Native(card, "PrepareUpgradeEffect", id)!, "remaining independent Mari effect " + id);card.UpgradeInternal();card.FinalizeUpgradeInternal(); }
