        TemplateReset();
        Check(!MariFlag(MariPolicy(), "Enabled"), "no permanent Mari means no shop benefits");
        var card = Mari();
        Player.PlayerCombatState!.Hand.AddInternal(card);
        Check(!MariFlag(MariPolicy(), "Enabled"), "a generated combat Mari copy cannot activate permanent shop benefits");
